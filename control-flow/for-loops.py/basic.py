# a for loop is used to iterate over items in a given sequence ( list , string , tupple )

key = input ("enter a text: ")

for i in key :   # iterates through every character in the string 
    print (i)
    
    
# to iterate over a given range of numbers we use the range function 
'''
the range finction has three parameters range (<start> , <stop> , <step> )
any parameter can be ignored at any time 
for exmaple 
'''

for i in range (10):
    print (i)
print ()

for i in range (3 , 10):
    print (i)
print()

for i in range (1 , 10 , 2 ):
    print (i)
print ()

